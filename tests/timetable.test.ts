import { describe, expect, it } from 'vitest';
import { MemoryFS } from '../src/lib/vault/fs';
import {
  courseCode, extractField, maintainAnnotated, parseIcs, syncTimetable, ttSanitize,
} from '../src/lib/vault/timetable';

const NOW = new Date('2026-11-17T12:00:00Z');
const OPTS = { outName: 'Brightspace', virtRoot: '! Index', daysPast: 14, daysFuture: 120 };

// A TimeEdit-style feed: UTC times, "Label: value" descriptions.
const ICS = [
  'BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//TimeEdit//EN',
  'BEGIN:VEVENT', 'UID:lec-1@timeedit',
  'DTSTART:20261118T074500Z', 'DTEND:20261118T093000Z',
  'SUMMARY:CSE12A Calculus: Lecture [1/2]',
  'DESCRIPTION:Course code: CSE12A\\nType: Lecture\\nStaff: Someone',
  'LOCATION:EEMCS-Hall Ampere', 'END:VEVENT',
  // summer time: 08:45 UTC is 10:45 in Amsterdam
  'BEGIN:VEVENT', 'UID:summer@timeedit',
  'DTSTART:20270301T084500Z', 'DTEND:20270301T103000Z',
  'SUMMARY:Mentor meeting', 'DESCRIPTION:Type: Mentor meeting', 'LOCATION:No Room (No Room)', 'END:VEVENT',
  // weekly, three times
  'BEGIN:VEVENT', 'UID:tut@timeedit',
  'DTSTART:20261119T124500Z', 'DTEND:20261119T143000Z', 'RRULE:FREQ=WEEKLY;COUNT=3',
  'SUMMARY:CSE12A Tutorial', 'DESCRIPTION:Course code: CSE12A/CSE11C\\nType: Tutorial', 'END:VEVENT',
  'BEGIN:VEVENT', 'UID:gone@timeedit', 'STATUS:CANCELLED',
  'DTSTART:20261120T074500Z', 'DTEND:20261120T093000Z', 'SUMMARY:Cancelled class', 'END:VEVENT',
  'BEGIN:VEVENT', 'UID:day@timeedit',
  'DTSTART;VALUE=DATE:20261121', 'DTEND;VALUE=DATE:20261122', 'SUMMARY:Holiday', 'END:VEVENT',
  'BEGIN:VEVENT', 'UID:old@timeedit',
  'DTSTART:20260901T074500Z', 'DTEND:20260901T093000Z', 'SUMMARY:Long ago', 'END:VEVENT',
  'END:VCALENDAR',
].join('\r\n');

describe('feed parsing', () => {
  it('reads TimeEdit description fields and course codes', () => {
    const desc = 'Course code: CSE12A extra\nType: Lecture\nStaff: A\nB';
    expect(extractField(desc, 'Type')).toBe('Lecture');
    expect(extractField(desc, 'Staff')).toBe('A B');
    expect(extractField(desc, 'Nope')).toBe('');
    expect(courseCode('whatever', desc)).toBe('CSE12A');
    expect(courseCode('CSE11A Reasoning and Logic', '')).toBe('CSE11A');
    expect(courseCode('Mentor meeting', '')).toBe('');
    expect(ttSanitize('CSE12A Calculus: Lecture [1/2] #x')).toBe('CSE12A Calculus Lecture 12 x');
  });

  it('converts to Amsterdam time, expands repeats, skips cancelled / all-day / out of window', () => {
    const events = parseIcs(ICS, new Date('2026-11-03T12:00:00Z'), new Date('2027-03-17T12:00:00Z'));
    expect(events.map((e) => `${e.day} ${e.start}-${e.end} ${e.summary}`)).toEqual([
      '2026-11-18 08:45-10:30 CSE12A Calculus: Lecture [1/2]',
      '2026-11-19 13:45-15:30 CSE12A Tutorial',
      '2026-11-26 13:45-15:30 CSE12A Tutorial',
      '2026-12-03 13:45-15:30 CSE12A Tutorial',
      '2027-03-01 09:45-11:30 Mentor meeting',
    ]);
  });
});

describe('syncTimetable', () => {
  async function vault(): Promise<MemoryFS> {
    const fs = new MemoryFS();
    fs.set('Brightspace/CSE12A - Calculus/CSE12A - Calculus.md', 'home');
    fs.set('Brightspace/CSE11C - Computer Organisation/x.md', 'home');
    return fs;
  }

  it('writes one calendar note per class, linked to the course', async () => {
    const fs = await vault();
    const res = await syncTimetable(fs, ICS, OPTS, NOW);
    expect(res.instances).toBe(5);
    expect((await fs.listFiles('Timetable'))).toEqual([
      '2026-11-18 0845-1030 CSE12A Calculus Lecture 12.md',
      '2026-11-19 1345-1530 CSE12ACSE11C CSE12A Tutorial.md',
      '2026-11-26 1345-1530 CSE12ACSE11C CSE12A Tutorial.md',
      '2026-12-03 1345-1530 CSE12ACSE11C CSE12A Tutorial.md',
      '2027-03-01 0945-1130 Mentor meeting.md',
    ]);
    expect(await fs.readText('Timetable/2026-11-18 0845-1030 CSE12A Calculus Lecture 12.md')).toBe(`---
title: "CSE12A Calculus: Lecture [1/2]"
date: 2026-11-18
startTime: "08:45"
endTime: "10:30"
course: CSE12A
codes: ["CSE12A"]
kind: Lecture
room: "EEMCS-Hall Ampere"
course_notes: ["[[Courses/CSE12A - Calculus]]"]
tags: [timetable, autogenerated/partial]
uid: "lec-1@timeedit"
---
<!-- auto-generated by timetable-mirror : do not edit, safe to re-run -->

<!-- AUTO:START -->
# CSE12A Calculus: Lecture [1/2]

> [!info]- 🕐 When & where
> **2026-11-18 · 08:45–10:30**
> EEMCS-Hall Ampere
> **Type:** Lecture

> [!warning]- ⛔ Auto-generated section
> Everything outside the AUTO markers is yours and is kept. Dragging on the calendar is reverted. Hand-made sessions go in \`Sessions/\`.

> [!note]- 🔗 Links
> - Course: [[Courses/CSE12A - Calculus]]
> - Notebook: [[Courses/CSE12A - Calculus Notebook|📓 CSE12A - Calculus Notebook]]
> - Brightspace: [[Brightspace/CSE12A - Calculus/CSE12A - Calculus]]
> - _No dated lecture note for this day yet._

<!-- AUTO:END -->

## Notes
`);
    const tutorial = (await fs.readText('Timetable/2026-11-19 1345-1530 CSE12ACSE11C CSE12A Tutorial.md'))!;
    expect(tutorial).toContain('codes: ["CSE12A", "CSE11C"]');
    expect(tutorial).toContain('> - Course: [[Courses/CSE12A - Calculus]] · [[Courses/CSE11C - Computer Organisation]]');
    const mentor = (await fs.readText('Timetable/2027-03-01 0945-1130 Mentor meeting.md'))!;
    expect(mentor).not.toContain('room:');
    expect(mentor).not.toContain('🔗 Links');
  });

  it('is stable, keeps class notes, and only prunes notes without writing', async () => {
    const fs = await vault();
    await syncTimetable(fs, ICS, OPTS, NOW);
    expect((await syncTimetable(fs, ICS, OPTS, NOW)).written).toEqual([]);

    const lecture = 'Timetable/2026-11-18 0845-1030 CSE12A Calculus Lecture 12.md';
    const noted = 'Timetable/2026-11-19 1345-1530 CSE12ACSE11C CSE12A Tutorial.md';
    fs.set(lecture, `${await fs.readText(lecture)}\nlimits recap\n`);
    fs.set(noted, `${await fs.readText(noted)}\nexercise 3 was hard\n`);
    fs.set('Timetable/my own file.md', 'not generated');

    // the tutorial series disappears from the feed
    const without = ICS.replace(/BEGIN:VEVENT\r\nUID:tut@[\s\S]*?END:VEVENT\r\n/, '');
    const res = await syncTimetable(fs, without, OPTS, NOW);
    expect(res.kept).toEqual([noted]);
    expect(res.pruned.sort()).toEqual([
      'Timetable/2026-11-26 1345-1530 CSE12ACSE11C CSE12A Tutorial.md',
      'Timetable/2026-12-03 1345-1530 CSE12ACSE11C CSE12A Tutorial.md',
    ]);
    expect(await fs.readText('Timetable/my own file.md')).toBe('not generated');
    const kept = (await fs.readText(lecture))!;
    expect(kept).toContain('## Notes\n\nlimits recap\n');
    expect(kept).toContain('annotated: true\ntags: [timetable, autogenerated/partial]');
  });

  it('links the student\'s own dated lecture note', async () => {
    const fs = await vault();
    fs.set('CSE12A Calculus.md', '---\nFolders:\n  - "[[! Index]]"\ntags: [x]\n---\nmy course note');
    fs.set('CSE12A - 2026-11-18 - limits.md', '---\nFolders:\n  - "[[CSE12A Calculus]]"\n---\nnotes');
    await syncTimetable(fs, ICS, OPTS, NOW);
    const note = (await fs.readText('Timetable/2026-11-18 0845-1030 CSE12A Calculus Lecture 12.md'))!;
    expect(note).toContain('lecture: "[[CSE12A - 2026-11-18 - limits]]"');
    expect(note).toContain('> - Lecture notes: [[CSE12A - 2026-11-18 - limits]]');
  });

  it('maintains the annotated flag', () => {
    const base = '---\ntitle: x\ntags: [t]\n---\nbody\n\n## Notes\n';
    expect(maintainAnnotated(base)).toBe(base);
    expect(maintainAnnotated(`${base}\nmine\n`)).toBe('---\ntitle: x\nannotated: true\ntags: [t]\n---\nbody\n\n## Notes\n\nmine\n');
  });
});
