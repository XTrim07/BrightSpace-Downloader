/**
 * Scanned courses -> the desired contents of the vault's output folder
 * (`Brightspace/`), as a pure path -> content map. Nothing is written here.
 *
 * Port of bsvault/notes.py + vault.py + extras.py: one note per item
 * (`## Contents` holds its text, `## MOC` links its children), original files
 * next to the notes. Output is kept byte-compatible with the Python pipeline
 * so an existing vault is adopted without churn.
 */

import { htmlToMd } from '../htmlmd';
import type { ScannedCourse, Selection, TreeNode } from '../model';
import { filterTree } from '../model';
import { TEXT_CAP } from '../scan';
import { cmpStr, label, sanitize, shortDate, stripChars } from '../util';
import { BASE } from '../valence';

export const AUTO_START = '<!-- AUTO:START -->';
export const AUTO_END = '<!-- AUTO:END -->';
/** Banner kept identical to the Python generator's. */
export const AUTO_TAG = '<!-- auto-generated by main.py : do not edit, safe to re-run -->\n';

export type Desired =
  | { kind: 'text'; text: string }
  | { kind: 'bytes'; bytes: Uint8Array; lastModified: string }
  | { kind: 'remote'; courseId: number; topicId: number | string; lastModified: string };

export interface BuildOptions {
  /** name of the output folder inside the vault, e.g. "Brightspace" */
  outName: string;
  virtFolder: boolean;
  /** vault-side note the top note nests under, e.g. "! Index" ('' = none) */
  virtRoot: string;
}

export interface CourseHome {
  code: string;
  vname: string;
  entries: number;
  files: number;
}

type Entry = ['note' | 'file' | 'bare', string, string];

function tagsLine(base: string[]): string {
  return `tags: [${[...base, 'autogenerated'].join(', ')}]`;
}

/** Folder name for a course: `<PREFIX> - <short name>`. */
export function courseVaultName(name: string, code: string): string {
  let short = (name || '').replace(/\s*\(20\d\d.*?\)\s*/g, '').trim();
  const prefix = code.split('+')[0];
  if (prefix.length > 1 && short.toUpperCase().startsWith(prefix.toUpperCase() + ' ')) {
    short = stripChars(short.slice(prefix.length), ' -–:\t\n');
  }
  return sanitize(short ? `${prefix} - ${short}` : code, 80);
}

function wl(target: string, disp?: string): string {
  const t = target.replace(/\|/g, '-');
  const last = t.split('/').pop()!;
  const d = label(disp || last);
  return d !== last ? `[[${t}|${d}]]` : `[[${t}]]`;
}

function mocLine(e: Entry): string {
  return e[0] === 'bare' ? `- [${label(e[2])}](${e[1]})` : `- ${wl(e[1], e[2])}`;
}

export function mocNote(
  title: string, upTarget: string, brightspaceId: number | string, code: string,
  contents: string, entries: Entry[], virtFolder: boolean,
): string {
  const lines = ['---', `up: [[${upTarget}]]`];
  if (virtFolder && upTarget) lines.push('Folders:', `  - "[[${upTarget}]]"`);
  lines.push(
    tagsLine(['brightspace']), `course_code: ${code}`, `brightspace_id: ${brightspaceId}`,
    '---', AUTO_TAG.trim(), '', `# ${label(title)}`, '', AUTO_START,
  );
  if ((contents || '').trim()) lines.push('## Contents', '', contents.trim(), '');
  if (entries.length) lines.push('## MOC', '', ...entries.map(mocLine));
  lines.push(AUTO_END);
  return lines.join('\n').replace(/\s+$/, '') + '\n';
}

class CourseBuilder {
  out = new Map<string, Desired>();

  constructor(
    private sc: ScannedCourse,
    private vname: string,
    private opts: BuildOptions,
    /** dir -> lowercased names already used there (note stems are unique per dir) */
    private used: Map<string, Set<string>>,
  ) {}

  private seen(dir: string): Set<string> {
    let s = this.used.get(dir);
    if (!s) this.used.set(dir, (s = new Set()));
    return s;
  }

  private noteStem(dir: string, title: string): string {
    const base = sanitize(title || 'untitled', 90) || 'untitled';
    const seen = this.seen(dir);
    let cand = base;
    for (let i = 2; seen.has(`${cand}.md`.toLowerCase()); i++) cand = `${base} (${i})`;
    seen.add(`${cand}.md`.toLowerCase());
    return cand;
  }

  private note(path: string, ...args: Parameters<typeof mocNote>): void {
    this.out.set(path, { kind: 'text', text: mocNote(...args) });
  }

  /** Place file topics first: they seed the per-directory name sets. */
  placeFiles(nodes: TreeNode[]): number {
    let n = 0;
    for (const node of nodes) {
      if (node.kind === 'file' && node.path) {
        const path = `${this.vname}/${node.path}`;
        const lastModified = node.lastModified || '';
        this.out.set(
          path,
          node.bytes
            ? { kind: 'bytes', bytes: node.bytes, lastModified }
            : { kind: 'remote', courseId: this.sc.course.id, topicId: node.id, lastModified },
        );
        const cut = path.lastIndexOf('/');
        this.seen(path.slice(0, cut)).add(path.slice(cut + 1).toLowerCase());
        n++;
      } else if (node.kind === 'module') {
        n += this.placeFiles(node.children || []);
      }
    }
    return n;
  }

  private viewerUrl(tid: number | string): string {
    return `${BASE}/d2l/le/content/${this.sc.course.id}/viewContent/${tid}/View`;
  }

  private emitTopic(dir: string, node: TreeNode, up: string): Entry {
    const title = node.title || 'untitled';
    const desc = (node.desc || '').trim();
    const { code } = this.sc;
    const vf = this.opts.virtFolder;
    if (node.kind === 'file') {
      const rel = `${this.vname}/${node.path}`;
      // PDFs and other binaries are linked, never converted to text.
      const text = node.bytes ? (node.text || '').trim().slice(0, TEXT_CAP) : '';
      const body = [desc, text].filter(Boolean).join('\n\n');
      if (body) {
        const stem = this.noteStem(dir, title);
        this.note(`${dir}/${stem}.md`, title, up, node.id, code, body, [['file', rel, title]], vf);
        return ['note', `${dir}/${stem}`, title];
      }
      return ['file', rel, title];
    }
    if (node.kind === 'page') {
      let body = '';
      try {
        body = node.text ? htmlToMd(node.text).trim() : '';
      } catch {
        body = '';
      }
      const full = [desc, body].filter(Boolean).join('\n\n');
      if (full) {
        const stem = this.noteStem(dir, title);
        this.note(`${dir}/${stem}.md`, title, up, node.id, code, full, [], vf);
        return ['note', `${dir}/${stem}`, title];
      }
      return ['bare', this.viewerUrl(node.id), title];
    }
    if (node.kind === 'link') {
      const full = [desc, `[${label(title)}](${node.url || ''})`].filter(Boolean).join('\n\n');
      const stem = this.noteStem(dir, title);
      this.note(`${dir}/${stem}.md`, title, up, node.id, code, full, [], vf);
      return ['note', `${dir}/${stem}`, title];
    }
    return ['bare', this.viewerUrl(node.id), title];
  }

  private emitModule(dir: string, node: TreeNode, up: string): Entry {
    const title = node.title || 'untitled';
    const children = node.children || [];
    const desc = (node.desc || '').trim();
    if (!desc && !children.length) {
      return ['bare', `${BASE}/d2l/le/content/${this.sc.course.id}/Home`, title];
    }
    const stem = this.noteStem(dir, title);
    const own = `${dir}/${stem}`;
    const kids = this.emitLevel(`${dir}/${node.name}`, own, children);
    this.note(`${dir}/${stem}.md`, title, up, node.id, this.sc.code, desc, kids, this.opts.virtFolder);
    return ['note', own, title];
  }

  emitLevel(dir: string, up: string, nodes: TreeNode[]): Entry[] {
    return nodes.map((child) =>
      child.kind === 'module' ? this.emitModule(dir, child, up) : this.emitTopic(dir, child, up),
    );
  }

  private frontmatter(extraTags: string[] = []): string {
    const home = `${this.vname}/${this.vname}`;
    const vf = this.opts.virtFolder ? `Folders:\n  - "[[${home}]]"\n` : '';
    return (
      `---\nup: [[${home}]]\n${vf}${tagsLine(['brightspace', ...extraTags])}\n` +
      `course_code: ${this.sc.code}\n---\n`
    );
  }

  private wrapExtra(heading: string, table: string): string {
    const content = `# ${heading} — ${label(this.sc.code)}\n\n${table}`.trim();
    return this.frontmatter() + AUTO_TAG + [AUTO_START, content, AUTO_END].join('\n') + '\n';
  }

  emitExtras(kids: Entry[], sel: Selection): void {
    const { sc, vname } = this;
    const assignments = sel.assignments ? assignmentsTable(sc.dropbox) : '';
    if (assignments) {
      this.out.set(`${vname}/Assignments.md`, { kind: 'text', text: this.wrapExtra('Assignments', assignments) });
      kids.push(['note', `${vname}/Assignments`, 'Assignments']);
    }
    const grades = sel.grades ? gradesTable(sc.grades) : '';
    if (grades) {
      this.out.set(`${vname}/Grades.md`, { kind: 'text', text: this.wrapExtra('Grades', grades) });
      kids.push(['note', `${vname}/Grades`, 'Grades']);
    }
    if (sel.announcements && sc.announcements) {
      const head = `# Announcements - ${sc.code}`;
      const at = sc.announcements.indexOf(head);
      let ann = sc.announcements;
      if (at >= 0) {
        ann =
          ann.slice(0, at) +
          this.frontmatter(['announcements']) +
          `${AUTO_TAG.trim()}\n${AUTO_START}\n# Announcements — ${label(sc.code)}` +
          ann.slice(at + head.length);
      }
      ann = ann.replace(/\s+$/, '') + `\n${AUTO_END}\n`;
      this.out.set(`${vname}/Announcements.md`, { kind: 'text', text: ann });
      kids.push(['note', `${vname}/Announcements`, 'Announcements']);
    }
  }
}

function flat(value: unknown): string {
  const s = String(value ?? '');
  return (s.includes('<') ? htmlToMd(s) : s).replace(/\s+/g, ' ');
}

export function gradesTable(data: any): string {
  const items = Array.isArray(data) ? data : (data?.Items ?? data?.Values ?? []);
  if (!Array.isArray(items)) return '';
  const rows: string[] = [];
  for (const g of items) {
    if (!g || typeof g !== 'object') continue;
    const name = g.GradeObjectName || g.Name || '';
    const num = g.PointsNumerator ?? g.Points ?? '';
    const den = g.PointsDenominator ?? g.MaxPoints ?? '';
    const score = den !== '' && den !== null ? `${num} / ${den}` : String(num);
    let feedback = g.Feedback ?? g.Comments ?? '';
    if (feedback && typeof feedback === 'object') feedback = feedback.Text ?? '';
    rows.push(`| ${label(String(name))} | ${label(score)} | ${label(flat(feedback).slice(0, 300))} |`);
  }
  if (!rows.length) return '';
  return ['| Item | Score | Feedback |', '| --- | --- | --- |', ...rows].join('\n');
}

export function assignmentsTable(boxes: Record<string, any>[] | null): string {
  if (!boxes?.length) return '';
  // The Python cache stores one JSON per folder and reads them back sorted by file name.
  const byFile = new Map<string, Record<string, any>>();
  for (const box of boxes) {
    if (box && typeof box === 'object') byFile.set(sanitize(box.Name ?? `folder-${box.Id}`), box);
  }
  const rows = [...byFile.keys()].sort(cmpStr).map((key) => {
    const box = byFile.get(key)!;
    const due = box.DueDate || box.DueDateTime || box.EndDate || '';
    let instr = box.CustomInstructions || box.Instructions || '';
    if (instr && typeof instr === 'object') instr = instr.Text ?? '';
    return `| ${label(box.Name ?? '')} | ${shortDate(due)} | ${label(flat(instr).slice(0, 400))} |`;
  });
  if (!rows.length) return '';
  return ['| Name | Due | Details |', '| --- | --- | --- |', ...rows].join('\n');
}

/** Top note listing every course: `<out>/! <out>.md`. */
export function vaultHome(homes: CourseHome[], opts: BuildOptions, today: string): string {
  const fm = ['---', tagsLine(['brightspace', 'moc'])];
  if (opts.virtFolder && opts.virtRoot) {
    fm.push(`up: [[${opts.virtRoot}]]`, 'Folders:', `  - "[[${opts.virtRoot}]]"`);
  }
  fm.push('---');
  const body = [
    `# ! ${opts.outName} Vault`, '',
    `Synced ${today}. One note per item: ` +
      '`## Contents` holds the item\'s own text, `## MOC` links its children. ' +
      'Your own notes live in the vault-side `Courses/` hub notes.',
    '', '## Courses', '',
    ...homes.map((h) => `- ${wl(`${h.vname}/${h.vname}`, h.code)} — ${h.entries} entries, ${h.files} files`),
  ];
  return [...fm, AUTO_TAG.trim(), AUTO_START, ...body, AUTO_END].join('\n') + '\n';
}

/**
 * Add the top note. Courses synced earlier but not scanned this run keep
 * their line (taken from the manifest), so a partial sync never drops them.
 */
export function addVaultHome(
  build: BuildResult,
  previous: Record<string, CourseHome>,
  scannedCodes: string[],
  opts: BuildOptions,
  today: string,
): CourseHome[] {
  const merged = new Map<string, CourseHome>();
  for (const [code, home] of Object.entries(previous)) {
    if (!scannedCodes.includes(code)) merged.set(code, home);
  }
  for (const home of build.homes) merged.set(home.code, home);
  const all = [...merged.values()];
  build.files.set(`! ${opts.outName}.md`, { kind: 'text', text: vaultHome(all, opts, today) });
  return all;
}

export interface BuildResult {
  /** path (relative to the output folder) -> desired content */
  files: Map<string, Desired>;
  homes: CourseHome[];
}

/** Build the desired output for the scanned courses (already hydrated). */
export function buildVault(courses: ScannedCourse[], sel: Selection, opts: BuildOptions): BuildResult {
  const files = new Map<string, Desired>();
  const homes: CourseHome[] = [];
  const used = new Map<string, Set<string>>();
  for (const sc of courses) {
    const vname = courseVaultName(sc.course.name, sc.code);
    const tree = filterTree(sc.course.id, sc.tree, sel);
    const b = new CourseBuilder(sc, vname, opts, used);
    b.placeFiles(tree);
    const home = `${vname}/${vname}`;
    const kids = b.emitLevel(vname, home, tree);
    b.emitExtras(kids, sel);
    if (!kids.length) continue;
    const hub = opts.virtFolder ? `Course hub: [[Courses/${vname}]]\n\n` : '';
    b.out.set(`${vname}/${vname}.md`, {
      kind: 'text',
      text: mocNote(sc.course.name || sc.code, `${opts.outName}/! ${opts.outName}`,
        sc.course.id, sc.code, hub, kids, opts.virtFolder),
    });
    let nFiles = 0;
    for (const [path, d] of b.out) {
      files.set(path, d);
      if (!path.toLowerCase().endsWith('.md') || d.kind !== 'text') nFiles++;
    }
    homes.push({ code: sc.code, vname, entries: kids.length, files: nFiles });
  }
  return { files, homes };
}
