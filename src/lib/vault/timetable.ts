/**
 * MyTimetable (TimeEdit ICS feed) -> `Timetable/` notes: the calendar.
 * Port of timetable-mirror/mirror.py.
 *
 * One note per class instance inside a rolling window. The frontmatter
 * (title/date/startTime/endTime) is what the Full Calendar plugin reads, so
 * the week view shows the classes and a click opens the note. Notes also
 * link to the course hub, its notebook and the Brightspace page.
 *
 * Existing notes are updated surgically: only the block between the AUTO
 * markers is regenerated, everything else (frontmatter, `## Notes`) is kept.
 */

import ICAL from 'ical.js';
import { AUTO_END, AUTO_START } from './build';
import type { VaultFS } from './fs';
import { readNotes, splitMarkers } from './hubs';

const BANNER = '<!-- auto-generated by timetable-mirror : do not edit, safe to re-run -->';
const TZ = 'Europe/Amsterdam';
const NO_ROOM = 'No Room (No Room)';

export interface ClassEvent {
  /** wall-clock time in Europe/Amsterdam */
  day: string; // YYYY-MM-DD
  start: string; // HH:MM
  end: string; // HH:MM
  summary: string;
  description: string;
  room: string;
  uid: string;
  /** for sorting and the window check */
  at: number;
}

/** Filesystem- and wikilink-safe stem: unsafe characters are deleted (not replaced). */
export function ttSanitize(name: string, limit = 100): string {
  const s = name.replace(/[\][^|#<>:/\\?*]/g, '').replace(/\s+/g, ' ').trim();
  return Array.from(s).slice(0, limit).join('') || 'untitled';
}

/** YAML double-quoted scalar. */
function yq(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, "'")}"`;
}

/** TimeEdit DESCRIPTION sections look like 'Label: value' runs. */
export function extractField(desc: string, label: string): string {
  const esc = label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const m = desc.match(new RegExp(`^${esc}:\\s*([\\s\\S]+?)(?=\\n[A-Z][^:\\n]*:|(?![\\s\\S]))`, 'm'));
  return m ? m[1].trim().replace(/\n/g, ' ') : '';
}

/** DESCRIPTION 'Course code:' first, else a SUMMARY prefix like CSE11A. */
export function courseCode(summary: string, desc: string): string {
  const field = extractField(desc, 'Course code');
  if (field) return field.split(/\s+/)[0];
  return summary.match(/^([A-Z]{1,4}\d{2,4}[A-Z]*)(\s|-|$)/)?.[1] ?? '';
}

const codeParts = (code: string) => code.split(/[/,]/).map((c) => c.trim()).filter(Boolean);

// ---------------------------------------------------------------- ICS

const fmt = new Intl.DateTimeFormat('en-CA', {
  timeZone: TZ, hourCycle: 'h23',
  year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit',
});

function amsterdam(date: Date): { day: string; time: string } {
  const p = Object.fromEntries(fmt.formatToParts(date).map((x) => [x.type, x.value]));
  return { day: `${p.year}-${p.month}-${p.day}`, time: `${p.hour}:${p.minute}` };
}

const pad = (n: number) => String(n).padStart(2, '0');

/** Feed times are UTC (or zoned): convert. Floating times are already local wall time. */
function local(time: any): { day: string; time: string; at: number } {
  const floating = !time.zone || time.zone.tzid === 'floating';
  if (floating) {
    const day = `${time.year}-${pad(time.month)}-${pad(time.day)}`;
    return { day, time: `${pad(time.hour)}:${pad(time.minute)}`, at: Date.parse(`${day}T${pad(time.hour)}:${pad(time.minute)}:00Z`) };
  }
  const date: Date = time.toJSDate();
  return { ...amsterdam(date), at: date.getTime() };
}

/**
 * Class instances of the feed inside [from, to]. Recurring events are
 * expanded; cancelled and all-day entries are skipped.
 */
export function parseIcs(raw: string, from: Date, to: Date): ClassEvent[] {
  const root = new ICAL.Component(ICAL.parse(raw));
  for (const tz of root.getAllSubcomponents('vtimezone')) ICAL.TimezoneService.register(tz);
  const all = root.getAllSubcomponents('vevent').map((v: any) => new ICAL.Event(v));
  const masters = all.filter((e: any) => !e.isRecurrenceException());
  const exceptions = all.filter((e: any) => e.isRecurrenceException());
  const orphans: any[] = [];
  for (const ex of exceptions) {
    const master = masters.find((m: any) => m.uid === ex.uid && m.isRecurring());
    if (master) master.relateException(ex);
    else orphans.push(ex);
  }

  const out: ClassEvent[] = [];
  const add = (item: any, startDate: any, endDate: any) => {
    const comp = item.component;
    if (String(comp.getFirstPropertyValue('status') ?? '').toUpperCase() === 'CANCELLED') return;
    if (!startDate || !endDate || startDate.isDate || endDate.isDate) return; // all-day / date-only
    if (!comp.hasProperty('dtend') && !comp.hasProperty('duration')) return;
    const s = local(startDate);
    const e = local(endDate);
    if (e.at <= from.getTime() || s.at >= to.getTime()) return;
    out.push({
      day: s.day, start: s.time, end: e.time, at: s.at,
      summary: String(item.summary ?? 'Untitled').trim(),
      description: String(item.description ?? ''),
      room: String(item.location ?? '').trim(),
      uid: String(item.uid ?? ''),
    });
  };

  for (const ev of [...masters, ...orphans]) {
    if (!ev.isRecurring()) {
      add(ev, ev.startDate, ev.endDate);
      continue;
    }
    const it = ev.iterator();
    for (let i = 0; i < 5000; i++) {
      const next = it.next();
      if (!next) break;
      const occ = ev.getOccurrenceDetails(next);
      if (local(occ.startDate).at >= to.getTime()) break;
      add(occ.item, occ.startDate, occ.endDate);
    }
  }
  return out.sort((a, b) => a.at - b.at || (a.uid < b.uid ? -1 : a.uid > b.uid ? 1 : 0));
}

// ---------------------------------------------------------------- notes

/** Sync the derived `annotated:` frontmatter line with the `## Notes` content. */
export function maintainAnnotated(text: string): string {
  const hasNotes = !!readNotes(text);
  const lines = text.split('\n');
  const end = lines.indexOf('---', 1);
  if (end < 0) return text;
  const fm = lines.slice(1, end).filter((l) => !l.startsWith('annotated:'));
  if (hasNotes) {
    const at = fm.findIndex((l) => l.startsWith('tags:'));
    fm.splice(at < 0 ? fm.length : at, 0, 'annotated: true');
  }
  return ['---', ...fm, ...lines.slice(end)].join('\n');
}

/** Replace (or, with null, drop) one `key: value` line of the frontmatter. */
function setFmLine(head: string, key: string, value: string | null): string {
  if (!head.startsWith('---')) return head;
  const end = head.indexOf('\n---', 3);
  if (end < 0) return head;
  const lines = head.slice(0, end).split('\n');
  const at = lines.findIndex((l) => l.startsWith(`${key}:`));
  if (value === null) {
    if (at >= 0) lines.splice(at, 1);
  } else if (at >= 0) lines[at] = `${key}: ${value}`;
  else {
    const tags = lines.findIndex((l) => l.startsWith('tags:'));
    lines.splice(tags < 0 ? lines.length : tags, 0, `${key}: ${value}`);
  }
  return lines.join('\n') + head.slice(end);
}

/** Frontmatter block of a note ('' when it has none). */
function frontmatter(text: string): string {
  if (!text.startsWith('---')) return '';
  const end = text.indexOf('---', 3);
  return end < 0 ? '' : text.slice(3, end);
}

/** Does the note's VirtFolder `Folders:` point at parent? */
function hasParent(text: string, parent: string): boolean {
  const fm = frontmatter(text);
  if (!fm) return false;
  return (fm.includes('tags:') ? fm.split('tags:')[0] : fm).includes(`[[${parent}]]`);
}

function isChildOf(text: string, parent: string): boolean {
  const fm = frontmatter(text);
  const m = fm.match(/^Folders:\s*(.*)$/m);
  if (!m) return false;
  const target = `[[${parent}]]`;
  if (m[1].trim()) return m[1].includes(target); // single-line form
  for (const line of fm.split('Folders:')[1].split('\n').slice(1)) {
    if (/^\s+-\s+/.test(line)) {
      if (line.includes(target)) return true;
    } else if (line.trim() !== '' && !line.startsWith(' ')) break;
  }
  return false;
}

/** What the notes link to: read from the vault once per sync. */
class VaultLinks {
  private dirs: string[] | null = null;
  private notes: Map<string, string> | null = null; // stem -> text (vault root + Excalidraw/)

  constructor(private fs: VaultFS, private outName: string, private root: string) {}

  private async rootNotes(): Promise<Map<string, string>> {
    if (this.notes) return this.notes;
    this.notes = new Map();
    for (const dir of ['', 'Excalidraw']) {
      for (const name of await this.fs.listFiles(dir)) {
        if (!name.endsWith('.md')) continue;
        this.notes.set(`${dir ? 'Excalidraw/' : ''}${name}`, (await this.fs.readText(dir ? `${dir}/${name}` : name)) ?? '');
      }
    }
    return this.notes;
  }

  /** [(Courses/<dir> hub link, stem of the student's own course note or null)] */
  async targets(code: string): Promise<[string, string | null][]> {
    this.dirs ??= (await this.fs.listDirs(this.outName)).sort();
    const out: [string, string | null][] = [];
    for (const part of codeParts(code)) {
      const dir = this.dirs.find((d) => d.startsWith(`${part} `));
      if (!dir) continue;
      const link = `Courses/${dir}`;
      if (out.some(([l]) => l === link)) continue;
      let scan: string | null = null;
      for (const [path, text] of [...(await this.rootNotes())].sort()) {
        if (!path.includes('/') && path.startsWith(`${part} `) && hasParent(text, this.root)) {
          scan = path.slice(0, -3);
          break;
        }
      }
      out.push([link, scan]);
    }
    return out;
  }

  /** The student's dated lecture note `<course> - YYYY-MM-DD( - title)?` for that day, if any. */
  async lectureNote(courseNotes: string[], day: string): Promise<string | null> {
    for (const parent of courseNotes) {
      for (const [path, text] of await this.rootNotes()) {
        if (!isChildOf(text, parent)) continue;
        const name = path.slice(path.lastIndexOf('/') + 1);
        const m = name.match(/^.+? - (\d{4}-\d{2}-\d{2})( - .*)?\.md$/);
        if (m && m[1] === day) return name.slice(0, -3);
      }
    }
    return null;
  }
}

export interface TimetableOptions {
  outName: string;
  /** vault-side root note of the student's own course notes */
  virtRoot: string;
  daysPast: number;
  daysFuture: number;
}

export interface TimetableResult {
  instances: number;
  written: string[];
  pruned: string[];
  /** stale notes kept because they contain the student's writing */
  kept: string[];
  /** course codes the calendar colours by */
  categories: string[];
  /** Full Calendar settings were updated (visible after restarting Obsidian) */
  calendarSetup?: boolean;
}

export async function syncTimetable(
  fs: VaultFS,
  ics: string,
  opts: TimetableOptions,
  now = new Date(),
): Promise<TimetableResult> {
  const day = 24 * 60 * 60 * 1000;
  const events = mergeGroups(parseIcs(ics, new Date(now.getTime() - opts.daysPast * day), new Date(now.getTime() + opts.daysFuture * day)));
  const links = new VaultLinks(fs, opts.outName, opts.virtRoot || '! Index');
  const result: TimetableResult = { instances: 0, written: [], pruned: [], kept: [], categories: [] };
  const seen = new Set<string>();
  const categories = new Set<string>();

  for (const ev of events) {
    const code = courseCode(ev.summary, ev.description);
    const kind = extractField(ev.description, 'Type');
    const room = ev.room;
    const { category, title } = calendarTitle(ev.summary, code);
    if (category) categories.add(category);
    const targets = await links.targets(code);
    const lecture = await links.lectureNote(targets.map(([, n]) => n).filter((n): n is string => !!n), ev.day);

    const core = ttSanitize(ev.summary, 60);
    // Upstream loses the space after the code here ("CSE12ALecture"); keep it.
    const prefix = code && core.startsWith(ttSanitize(code)) ? '' : code ? `${ttSanitize(code, 24)} ` : '';
    const stem = `${ev.day} ${ev.start.replace(':', '')}-${ev.end.replace(':', '')} ${prefix}${core}`;
    let name = `${stem}.md`;
    for (let i = 2; seen.has(name.toLowerCase()); i++) name = `${stem} (${i}).md`;
    seen.add(name.toLowerCase());
    const path = `Timetable/${name}`;

    const fm = ['---', `title: ${yq(title)}`, `date: ${ev.day}`,
      `startTime: "${ev.start}"`, `endTime: "${ev.end}"`];
    if (code) {
      fm.push(`course: ${code}`, `codes: [${codeParts(code).map((p) => `"${p}"`).join(', ')}]`);
    }
    if (kind) fm.push(`kind: ${kind}`);
    if (room) fm.push(`room: ${yq(room)}`);
    if (targets.length) fm.push(`course_notes: [${targets.map(([t]) => `"[[${t}]]"`).join(', ')}]`);
    if (lecture) fm.push(`lecture: "[[${lecture}]]"`);
    fm.push('tags: [timetable, autogenerated/partial]', `uid: ${yq(ev.uid)}`, '---');

    // Kept short on purpose: date and time are already in the calendar.
    const auto = [`# ${ev.summary}`, ''];
    const where = [room && `📍 ${room}`, kind].filter(Boolean).join(' · ');
    if (where) auto.push(where, '');
    for (const [t] of targets) {
      const d = t.slice(t.indexOf('/') + 1);
      auto.push(`[[${t}|📚 ${d}]] · [[Courses/${d} Notebook|📓 Notebook]] · [[${opts.outName}/${d}/${d}|Brightspace]]`, '');
    }
    if (lecture) auto.push(`✏️ [[${lecture}]]`, '');
    const body = auto.join('\n');

    const old = await fs.readText(path);
    let text: string;
    if (old !== null) {
      // Surgical: keep head (incl. frontmatter) and tail verbatim.
      let [head, , tail] = splitMarkers(old);
      // Title and room are ours too: the calendar shows the title, merged groups add rooms.
      head = setFmLine(setFmLine(head, 'title', yq(title)), 'room', room ? yq(room) : null);
      text = maintainAnnotated(`${head}${AUTO_START}\n${body}\n${AUTO_END}\n${tail}`);
    } else {
      text = [...fm, BANNER, '', AUTO_START, body, AUTO_END, '', '## Notes', ''].join('\n');
    }
    text = text.replace(/\s+$/, '') + '\n';
    if (text !== old) {
      await fs.write(path, text);
      result.written.push(path);
    }
    result.instances++;
  }

  // Prune instances gone from the feed; never delete a note with the student's writing.
  for (const name of (await fs.listFiles('Timetable')).sort()) {
    if (!name.endsWith('.md') || seen.has(name.toLowerCase())) continue;
    const text = (await fs.readText(`Timetable/${name}`)) ?? '';
    if (!text.includes('auto-generated by timetable-mirror')) continue; // not ours
    // The empty `## Notes` heading every note starts with is not writing.
    // (Upstream counts it, so it never prunes anything.)
    const own = splitMarkers(text)[2].split('\n').filter((l) => !/^## Notes\s*$/.test(l)).join('\n');
    if (own.trim()) result.kept.push(`Timetable/${name}`);
    else {
      await fs.remove(`Timetable/${name}`);
      result.pruned.push(`Timetable/${name}`);
    }
  }
  result.categories = [...categories].sort();
  return result;
}

/**
 * The same class given to several groups at once (same title and time,
 * different rooms) comes in as separate events: one note, all rooms.
 */
export function mergeGroups(events: ClassEvent[]): ClassEvent[] {
  const byKey = new Map<string, ClassEvent>();
  for (const ev of events) {
    const room = ev.room && ev.room !== NO_ROOM ? ev.room : '';
    const key = `${ev.day}|${ev.start}|${ev.end}|${ev.summary}`;
    const had = byKey.get(key);
    if (!had) byKey.set(key, { ...ev, room });
    else if (room && !had.room.split(', ').includes(room)) had.room = had.room ? `${had.room}, ${room}` : room;
  }
  return [...byKey.values()];
}

/**
 * Title as Full Calendar's categories expect it: `CODE - rest`. The calendar
 * then colours the class by course and shows only `rest`.
 */
export function calendarTitle(summary: string, code: string): { category: string; title: string } {
  const category = codeParts(code)[0] ?? '';
  if (!category) return { category: '', title: summary };
  let rest = summary;
  for (const lead of [code, category]) {
    if (rest.startsWith(lead)) {
      rest = rest.slice(lead.length);
      break;
    }
  }
  rest = rest.replace(/^[\s\-–:]+/, '').trim();
  return { category, title: rest ? `${category} - ${rest}` : category };
}

