const FC_DATA = '.obsidian/plugins/full-calendar-remastered/data.json';
/** distinct on a dark background, readable with white text */
const PALETTE = ['#2e7d32', '#1e88e5', '#c62828', '#ef6c00', '#8e24aa', '#00897b',
  '#9e9d24', '#6d4c41', '#d81b60', '#3949ab', '#0097a7', '#558b2f', '#f9a825', '#5e35b1'];

/**
 * Point Full Calendar (Remastered) at `Timetable/` and give every course its
 * own colour. Only adds what is missing: calendars, categories and colours
 * the student set up are left alone. Returns whether the settings changed.
 * Obsidian reads them when it starts, so a change shows after a restart.
 */
export async function setupFullCalendar(fs: VaultFS, categories: string[]): Promise<boolean> {
  const raw = await fs.readText(FC_DATA);
  if (raw === null) return false; // plugin not installed
  let d: any;
  try {
    d = JSON.parse(raw);
  } catch {
    return false;
  }
  if (!d || typeof d !== 'object') return false;
  const before = JSON.stringify(d);

  const sources: any[] = Array.isArray(d.calendarSources) ? d.calendarSources : [];
  if (!sources.some((s) => s?.type === 'local' && s.directory === 'Timetable')) {
    const ids = new Set(sources.map((s) => s?.id));
    let n = 1;
    while (ids.has(`local_${n}`)) n++;
    sources.push({ type: 'local', id: `local_${n}`, name: 'Timetable', directory: 'Timetable', color: '#7c3aed' });
    d.defaultCalendarId ??= `local_${n}`;
  }
  d.calendarSources = sources;

  if (categories.length) {
    d.enableAdvancedCategorization = true;
    const cats: any[] = Array.isArray(d.categorySettings) ? d.categorySettings : [];
    const used = new Set(cats.map((c) => c?.color));
    for (const name of categories) {
      if (cats.some((c) => c?.name === name)) continue;
      const color = PALETTE.find((p) => !used.has(p)) ?? PALETTE[cats.length % PALETTE.length];
      used.add(color);
      cats.push({ name, color });
    }
    d.categorySettings = cats;
  }

  if (JSON.stringify(d) === before) return false;
  await fs.write(FC_DATA, `${JSON.stringify(d, null, 2)}\n`);
  return true;
}
