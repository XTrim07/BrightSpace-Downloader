/**
 * Vault-side course hubs: one note per Brightspace course in `Courses/`.
 * Port of timetable-mirror/courses.py.
 *
 * Each hub has an AUTO block (course meta, Brightspace link, upcoming-classes
 * Dataview table) wrapped in markers, plus a free user space (`## Notes`).
 * Regeneration rewrites ONLY the marked block; everything else is preserved.
 * Each hub also gets a Notebook child listing every annotated class note.
 *
 * The student's own notes live here, never inside the Brightspace clone.
 */

import { AUTO_END, AUTO_START } from './build';
import type { VaultFS } from './fs';

export const HUB_PARENT = '! Course Notes';
export const HUB_BANNER =
  '<!-- auto-generated by courses-hub : user content outside markers is preserved -->';

function tagsLine(base: string[], partial = false): string {
  return `tags: [${[...base, partial ? 'autogenerated/partial' : 'autogenerated'].join(', ')}]`;
}

/** Python `s.split(sep, n)`. */
function splitN(s: string, sep: string, n: number): string[] {
  const out: string[] = [];
  let rest = s;
  for (let i = 0; i < n; i++) {
    const at = rest.indexOf(sep);
    if (at < 0) break;
    out.push(rest.slice(0, at));
    rest = rest.slice(at + sep.length);
  }
  out.push(rest);
  return out;
}

/** Text after the leading frontmatter block (the whole text when there is none). */
function bodyOf(text: string): string {
  return text.startsWith('---') ? (splitN(text, '---', 2)[2] ?? '') : text;
}

/**
 * Split marked text into (head, auto, tail): head = everything before the
 * START line, auto = lines between the markers, tail = everything after the
 * END line (user-owned). (text, '', '') when the marker pair is absent.
 */
export function splitMarkers(text: string): [string, string, string] {
  const start = text.indexOf(AUTO_START);
  if (start < 0) return [text, '', ''];
  const end = text.indexOf(AUTO_END, start);
  if (end < 0) return [text, '', ''];
  const headEnd = text.lastIndexOf('\n', start - 1) + 1;
  const autoStart = text.indexOf('\n', start) + 1;
  const autoEnd = text.lastIndexOf('\n', end - 1);
  const tailNl = text.indexOf('\n', end + AUTO_END.length);
  const tailStart = tailNl < 0 ? text.length : tailNl + 1;
  return [text.slice(0, headEnd), text.slice(autoStart, Math.max(autoStart, autoEnd)), text.slice(tailStart)];
}

/** Body of the last `## Notes` section ('' when absent or empty). */
export function readNotes(text: string): string {
  const lines = text.split('\n');
  let start = -1;
  for (let i = lines.length - 1; i >= 0; i--) {
    if (/^## Notes\s*$/.test(lines[i])) {
      start = i;
      break;
    }
  }
  if (start < 0) return '';
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((l) => l.startsWith('# '));
  return (end < 0 ? rest : rest.slice(0, end)).join('\n').trim();
}

const CLASSES_TABLE =
  'TABLE WITHOUT ID dateformat(date, "dd-MM") + " " + startTime AS When, ' +
  'link(file.link, title) AS Class, join(course_notes, " · ") AS Course, room AS Room, lecture AS Notes';

function parentAuto(): string[] {
  return [
    '## Upcoming classes', '',
    '> [!note]- 📚 Imported classes',
    '> Live Timetable mirror — hand-made `Sessions/` blocks excluded.',
    '',
    '```dataview', CLASSES_TABLE, 'FROM "Timetable"', 'WHERE date >= date(today)',
    'SORT date ASC, startTime ASC', 'LIMIT 30', '```',
  ];
}

const GROUPING = 'Grouping note for the per-course hubs below — nothing else lives here.';

/** The grouping note above all hubs: only its AUTO block is regenerated. */
export function hubParentText(existing: string | null, virtRoot: string): string {
  let fixed: string[];
  if (existing !== null) {
    let raw: string[];
    if (existing.includes(AUTO_START) && existing.includes(AUTO_END)) {
      const [head, , tail] = splitMarkers(existing);
      raw = `${bodyOf(head)}\n${tail}`.split('\n');
    } else {
      raw = bodyOf(existing).split('\n');
    }
    fixed = raw.filter((ln) => ln.trim() && !ln.includes('auto-generated by'));
    fixed = fixed.map((ln) => (ln.trim() === '# Course Notes' ? `# ${HUB_PARENT}` : ln));
    if (!fixed.some((ln) => ln.startsWith('# '))) fixed = [`# ${HUB_PARENT}`, '', ...fixed];
    if (!fixed.some((ln) => ln.includes('Grouping note'))) fixed.push('', GROUPING);
  } else {
    // Same shape a regeneration produces, so the next sync leaves it alone.
    fixed = [`# ${HUB_PARENT}`, GROUPING];
  }
  const fm = ['---', `title: ${HUB_PARENT}`, tagsLine(['course-index', 'moc'], true)];
  if (virtRoot) fm.push('Folders:', `  - "[[${virtRoot}]]"`);
  fm.push('---');
  return [...fm, HUB_BANNER, '', ...fixed, '', AUTO_START, ...parentAuto(), AUTO_END]
    .join('\n').replace(/\s+$/, '') + '\n';
}

function hubAuto(outName: string, dirname: string, code: string, nClasses: number, next: string | null): string[] {
  return [
    '## Upcoming classes', '',
    '> [!note]- 📚 Course material',
    `> - **Code:** ${code}`,
    `> - Brightspace: [[${outName}/${dirname}/${dirname}]] (read-only)`,
    `> - Notebook: [[Courses/${dirname} Notebook|📓 ${dirname} Notebook]]`,
    `> - Timetable: ${nClasses} upcoming classes${next ? `, next ${next}` : ''}`,
    '',
    '```dataview', CLASSES_TABLE, 'FROM "Timetable"',
    `WHERE contains(codes, "${code}") AND date >= date(today)`,
    'SORT date ASC, startTime ASC', 'LIMIT 10', '```',
  ];
}

/** A brand-new hub: frontmatter + title + AUTO block + empty `## Notes`. */
function hubText(dirname: string, code: string, auto: string[]): string {
  const fm = ['---', `title: ${dirname}`, `code: ${code}`, tagsLine(['course'], true),
    'Folders:', `  - "[[${HUB_PARENT}]]"`, '---'];
  const body = [HUB_BANNER, '', `# ${dirname}`, '', AUTO_START, ...auto, AUTO_END, '', '## Notes', ''];
  return [...fm, ...body].join('\n').replace(/\s+$/, '') + '\n';
}

/** Existing hub: keep head and tail verbatim, regenerate only between the markers. */
export function updateHub(existing: string, auto: string[]): string {
  let [head, , tail] = splitMarkers(existing);
  head = head.replace('- "[[! Index]]"', `- "[[${HUB_PARENT}]]"`)
    .replace('- "[[Course Notes]]"', `- "[[${HUB_PARENT}]]"`);
  return `${head}${AUTO_START}\n${auto.join('\n')}\n${AUTO_END}\n${tail}`.replace(/\s+$/, '') + '\n';
}

/** Live notebook: Dataview renders the `## Notes` of every class note of the course. */
export function notebookText(dirname: string, code: string): string {
  const fm = ['---', `title: ${dirname} Notebook`, `code: ${code}`, tagsLine(['course-notebook']),
    'view-mode-lock: reading', 'Folders:', `  - "[[Courses/${dirname}]]"`, '---'];
  const body = [
    HUB_BANNER, '', AUTO_START,
    `# ${dirname} — Notebook`, '',
    '> [!info]- 📓 Annotated class notes, oldest first',
    '> Live view — updates as you type in class notes. Write there; this note is read-only.',
    '',
    '```dataviewjs',
    `const CODE = ${JSON.stringify(code)};`,
    'const pages = dv.pages(\'"Timetable"\')',
    '  .where(p => p.codes && p.codes.includes(CODE))',
    "  .sort(p => p.file.name, 'asc');",
    'let shown = 0;',
    'for (const p of pages) {',
    '  const text = await dv.io.load(p.file.path);',
    "  const lines = text.split('\\n');",
    '  let start = -1;',
    '  for (let i = lines.length - 1; i >= 0; i--) {',
    '    if (/^## Notes\\s*$/.test(lines[i])) { start = i; break; }',
    '  }',
    "  let content = '';",
    '  if (start >= 0) {',
    '    const rest = lines.slice(start + 1);',
    '    let end = rest.findIndex(l => /^# /.test(l));',
    '    content = (end < 0 ? rest : rest.slice(0, end))',
    "      .join('\\n').trim();",
    '  }',
    '  if (!content) continue;',
    '  shown++;',
    "  const label = (p.date && p.date.toISODate ? p.date.toISODate() : p.date) + ' ' + (p.startTime || '') + ' — ' + (p.title || p.file.name);",
    "  dv.header(2, '[[' + p.file.path + '|' + label.replace(/\\|/g, '-') + ']]');",
    '  dv.paragraph(content);',
    '}',
    "if (!shown) dv.paragraph('_No annotated class notes yet — write under `## Notes` in any class note._');",
    '```',
    AUTO_END, '',
  ];
  return [...fm, ...body].join('\n').replace(/\s+$/, '') + '\n';
}

/** (upcoming count, next date) of the course's classes, when a Timetable/ mirror exists. */
async function timetableStats(fs: VaultFS, code: string, today: string): Promise<[number, string | null]> {
  let n = 0;
  let next: string | null = null;
  for (const name of await fs.listFiles('Timetable')) {
    if (!name.endsWith('.md')) continue;
    const text = (await fs.readText(`Timetable/${name}`)) ?? '';
    const fm = splitN(text, '---', 2)[1] ?? '';
    const field = (key: string) =>
      (fm.match(new RegExp(`^${key}:\\s*(.*)$`, 'm'))?.[1] ?? '').trim().replace(/^["']|["']$/g, '');
    if (!field('course').split('/').map((c) => c.trim()).includes(code)) continue;
    const day = field('date');
    if (day >= today) {
      n++;
      if (next === null || day < next) next = day;
    }
  }
  return [n, next];
}

export interface HubsResult {
  written: string[];
  pruned: string[];
}

/** Write a file only when its content differs, so untouched notes keep their timestamps. */
async function put(fs: VaultFS, path: string, text: string, changed: string[]): Promise<void> {
  if ((await fs.readText(path)) !== text) {
    await fs.write(path, text);
    changed.push(path);
  }
}

/**
 * Create / refresh the hubs for every course folder inside the output folder.
 * Hubs of vanished courses are pruned only when their `## Notes` is empty.
 */
export async function syncHubs(
  fs: VaultFS,
  outName: string,
  virtRoot: string,
  today = new Date().toISOString().slice(0, 10),
): Promise<HubsResult> {
  const result: HubsResult = { written: [], pruned: [] };
  const live = (await fs.listDirs(outName)).sort();
  if (!live.length) return result;

  const parentPath = `${HUB_PARENT}.md`;
  let parent = await fs.readText(parentPath);
  if (parent === null) {
    // one-time migration of the legacy name
    const legacy = await fs.readText('Course Notes.md');
    if (legacy !== null) {
      parent = legacy;
      await fs.remove('Course Notes.md');
    }
  }
  await put(fs, parentPath, hubParentText(parent, virtRoot), result.written);

  for (const dirname of live) {
    const code = dirname.split(' - ')[0];
    const [n, next] = await timetableStats(fs, code, today);
    const auto = hubAuto(outName, dirname, code, n, next);
    const path = `Courses/${dirname}.md`;
    const existing = await fs.readText(path);
    await put(fs, path, existing === null ? hubText(dirname, code, auto) : updateHub(existing, auto), result.written);
    await put(fs, `Courses/${dirname} Notebook.md`, notebookText(dirname, code), result.written);
  }

  for (const name of (await fs.listFiles('Courses')).sort()) {
    if (!name.endsWith('.md')) continue;
    const stem = name.slice(0, -3);
    const isNotebook = stem.endsWith(' Notebook');
    const base = isNotebook ? stem.slice(0, -' Notebook'.length) : stem;
    if (live.includes(base)) continue;
    const text = (await fs.readText(`Courses/${name}`)) ?? '';
    // Only ever touch notes this tool generated: Courses/ may hold other files.
    if (!text.includes('auto-generated by courses-hub')) continue;
    if (isNotebook || !readNotes(bodyOf(text))) {
      await fs.remove(`Courses/${name}`);
      result.pruned.push(`Courses/${name}`);
    }
  }
  return result;
}
